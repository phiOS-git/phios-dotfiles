# phiOS — the runtime pointer to this checkout.
#
# `phi` and phi-shell resolve the repo as $PHI_DOTFILES, else ~/phios-dotfiles.
# Default is right on a standard machine, but a checkout elsewhere (dev tree)
# leaves tools unable to find it without obvious error. The installer always
# knows where this checkout is ($PHIOS_ROOT) and writes that path where every
# phiOS process can pick it up:
#
#   ~/.config/phios/dotfiles-root          read by ~/.zshenv; TTY login shell,
#                                          Hyprland, and quickshell get it
#   ~/.config/environment.d/10-phios.conf  systemd user environment
#
# Both are derived machine state, not repository content. Not tracked in the
# state manifest; `--check` only reports a stale value, never reconciles.
#
# Dependency budget: bash + coreutils only.

phios_env_paths() {
	local cfg=${XDG_CONFIG_HOME:-$HOME/.config}
	PHIOS_ENV_ROOT_FILE=$cfg/phios/dotfiles-root
	PHIOS_ENV_D_FILE=$cfg/environment.d/10-phios.conf
}

# The path currently recorded, or empty.
phios_env_current() {
	phios_env_paths
	if [[ -r $PHIOS_ENV_ROOT_FILE ]]; then
		head -n1 -- "$PHIOS_ENV_ROOT_FILE"
	fi
}

phios_env_report() {
	local current
	phios_env_paths
	current=$(phios_env_current)
	phios_out ''
	phios_out 'environment'
	if [[ $current == "$PHIOS_ROOT" ]]; then
		phios_out "  PHI_DOTFILES already points here"
		return 0
	fi
	if [[ -n $current ]]; then
		phios_out "  update   PHI_DOTFILES  $current  ->  $PHIOS_ROOT"
	else
		phios_out "  write    PHI_DOTFILES  ->  $PHIOS_ROOT"
	fi
	phios_out "           $PHIOS_ENV_ROOT_FILE"
	phios_out "           $PHIOS_ENV_D_FILE"
	PHIOS_DRIFT=$((PHIOS_DRIFT + 1))
}

phios_env_write() {
	phios_env_paths
	phios_out ''
	phios_out 'environment'
	if [[ $(phios_env_current) == "$PHIOS_ROOT" ]]; then
		phios_out "  PHI_DOTFILES already points here ($PHIOS_ROOT)"
		return 0
	fi
	mkdir -p -- "$(dirname -- "$PHIOS_ENV_ROOT_FILE")" \
	            "$(dirname -- "$PHIOS_ENV_D_FILE")"
	printf '%s\n' "$PHIOS_ROOT" > "$PHIOS_ENV_ROOT_FILE"
	{
		printf '# Generated by phios-install — the phios-dotfiles checkout on this\n'
		printf '# machine, for the systemd user session (quickshell, and anything\n'
		printf '# the graphical session starts). See bin/lib/env.sh.\n'
		printf 'PHI_DOTFILES=%s\n' "$PHIOS_ROOT"
	} > "$PHIOS_ENV_D_FILE"
	phios_out "  $PHIOS_ENV_ROOT_FILE"
	phios_out "  $PHIOS_ENV_D_FILE"
	phios_out "  picked up on the next login (or now: systemctl --user import-environment PHI_DOTFILES)"
}
